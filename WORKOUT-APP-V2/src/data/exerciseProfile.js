const parse = text => (text ?? '').trim().split(/\s+/).filter(Boolean).map(p => p.split(':')).map(([m, r]) => [m, Number(r)])

// { [id]: { group, primary: [muscle], secondary: [muscle], ratings: { [muscle]: 1–3 } } }
export const PROFILE = Object.fromEntries(Object.entries(RAW).map(([id, line]) => {
  const [group, primary, secondary] = line.split('|').map(s => s.trim())
  const p = parse(primary)
  const s = parse(secondary)
  return [id, { group, primary: p.map(([m]) => m), secondary: s.map(([m]) => m), ratings: Object.fromEntries([...p, ...s]) }]
}))
